val MaterialTheme.spacing: Spacing
    @Composable
    @ReadOnlyComposable
    get() = LocalSpacing.current

val MaterialTheme.elevations: ElevationTokens
    @Composable
    @ReadOnlyComposable
    get() = LocalElevations.current

@Composable
fun PriceBridgeTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    // Dynamic color OFF, brand colors ON per design system specification
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    CompositionLocalProvider(
        LocalSpacing provides Spacing(),
        LocalElevations provides ElevationTokens()
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = PriceBridgeTypography,
            shapes = PriceBridgeShapes,
            content = content
        )
    }
}

// Backward compatibility alias
@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    PriceBridgeTheme(darkTheme = darkTheme, content = content)
}
